import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const read = name => readFileSync(new URL(name, root), 'utf8');
const html = read('index.html');
const css = read('styles.css');
const script = read('game.js').replace(/<\/script/gi, '<\\/script');
const icon = `data:image/svg+xml,${encodeURIComponent(read('favicon.svg').trim())}`;
const output = html
  .replace('<!doctype html>', '<!doctype html>\n<!-- Generated by scripts/build-standalone.mjs; edit index.html, styles.css, and game.js. -->')
  .replace(/<link rel="icon" type="image\/svg\+xml" href="favicon.svg" \/>/, `<link rel="icon" type="image/svg+xml" href="${icon}" />`)
  .replace(/<link rel="stylesheet" href="styles\.css(?:\?[^"]*)?" \/>/, () => `<style>\n${css}</style>`)
  .replace(/<script src="game\.js(?:\?[^"]*)?"><\/script>/, () => `<script>\n${script}</script>`);

if (output.includes('href="styles.css') || output.includes('src="game.js')) {
  throw new Error('Could not inline the game sources. Check the tags in index.html.');
}
if (process.argv.includes('--check')) {
  if (read('Purrchinko-Standalone.html') !== output) {
    console.error('Standalone is out of date. Run node scripts/build-standalone.mjs.');
    process.exitCode = 1;
  }
} else {
  writeFileSync(new URL('Purrchinko-Standalone.html', root), output);
  console.log('Built Purrchinko-Standalone.html');
}
